  HAL_Delay(1000);   /* đợi cảm biến ổn định sau init */

  /* ===== HIỆU CHUẨN MAG (xoay board 360° trong 20s) ===== */
  printf("\r\n===== HIEU CHUAN MAG =====\r\n");
  printf("Xoay board 360 do (moi huong) trong 20 giay...\r\n");
  ICM_CalibrateMag();
  printf("Hieu chuan xong!\r\n");
